def main():
    img = Image.new("L", (W, H), BG)
    d = ImageDraw.Draw(img)

    # 时钟区参考框(和固件里 CLK_BG_* 一致)
    BGX0, BGX1, BGY0, BGY1 = 30, 370, 44, 122

    rows = [
        ("A  4x8 x6   网格 3px   笔画 6px   <- 现在这版(太粗)",
         DIG_4x8, 6, 3, 6, 24),
        ("B  8x16 x3  网格 3px   笔画 3px   <- 同尺寸,笔画减半",
         DIG_8x16, 3, 3, 6, 12),
    ]

    y = 8
    for name, glyphs, scale, grid, pad, colonw in rows:
        label(d, name, 10, y)
        y += 20

        gh = len(glyphs["0"]) * scale
        gy = y + max(0, (78 - gh) // 2)
        d.rectangle([BGX0, y, BGX1, y + 77], fill=BG)
        draw_grid(d, BGX0, y, BGX1, y + 77, grid)

        gw_num = len(glyphs["0"][0]) * scale
        total = 6 * gw_num + 2 * colonw + 5 * pad
        x0 = (W - total) // 2
        x0 = x0 - (x0 - BGX0) % grid          # 起点压在网格上
        draw_clock(d, "12:34:56", x0, gy, glyphs, scale, pad, colonw)

        d.rectangle([BGX0, y, BGX1, y + 77], outline=INK)
        label(d, f"数字 {gw_num}x{gh}   整串宽 {total}", 10, y + 80)
        y += 105

    # ---- C:字更大、网格更疏 ----
    label(d, "C  8x16 x4  网格 4px   笔画 4px   数字 32x64(要重排时钟区)",
          10, y)
    y += 20
    scale, grid, pad, colonw = 4, 4, 8, 12
    gh = 16 * scale
    d.rectangle([BGX0, y, BGX1, y + 77], fill=BG)
    draw_grid(d, BGX0, y, BGX1, y + 77, grid)
    gy = y + (77 - gh) // 2
    total = 6 * (8 * scale) + 2 * colonw + 5 * pad
    x0 = (W - total) // 2 - (W - total) // 2 % grid
    draw_clock(d, "12:34:56", x0, gy, DIG_8x16, scale, pad, colonw)
    d.rectangle([BGX0, y, BGX1, y + 77], outline=INK)
    label(d, f"数字 {8*scale}x{gh}   整串宽 {total}", 10, y + 80)

    img.save(OUT)
    print(f"已保存 {OUT}  {img.size[0]}x{img.size[1]}")


def export_c_header():
    """导出成固件用的 C 头文件(8x16,每行一个字节,MSB 在左)"""
    path = os.path.join(
        r"L:\ESP32\projects\ESP32-S3-RLCD-4.2\02_Example\ESP-IDF"
        r"\11_U8G2_Test\components\ui_draw",
        "ui_clock_bits.h")

    L = [
        "/*",
        " * 方块点阵时钟的数字字形 —— 由 tools/fontgen/clock_bitmap_v3.py 生成,别手改。",
        " *",
        " * 8 宽 x 16 高,每行一个字节,MSB 在左。显示时整数字放大 3 倍 =>",
        " * 每个设计点 = 3x3 屏幕像素 = 【1 个背景网格格】。",
        " *",
        " * 为什么是 16 行(而不是更省事的 8 行):",
        " *   点阵字里笔画的观感粗细 = 笔画厚度 / 数字高度 = 1 / 行数。",
        " *   8 行  -> 1/8  = 12.5%,放大 6 倍后笔画 6px,数字才 24px 宽,",
        " *           一块墨占了 1/4 宽度,远看就是\"胖\"。",
        " *   16 行 -> 1/16 =  6.3%,放大 3 倍后笔画 3px,同样 48px 高,",
        " *           笔画只有原来一半 —— 这才是正常数字的轻重。",
        " * 数字显示高度被时钟区锁死在 48px,所以行数翻倍 = 放大倍数减半,",
        " * 而这恰好也让一个设计点从 2x2 格缩成 1 格,网格和数字仍然同节拍。",
        " *",
        " * 点阵天然等宽,秒跳时不会左右抖。",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#define CLK_BM_W   8",
        "#define CLK_BM_H   16",
        "",
        "static const uint8_t kClkDigit[10][CLK_BM_H] = {",
    ]

    for ch in "0123456789":
        L.append(f"    {{  /* {ch} */")
        vals = []
        for row in DIG_8x16[ch]:
            v = 0
            for c, p in enumerate(row):
                if p == "#":
                    v |= 0x80 >> c
            vals.append(f"0x{v:02X}")
        L.append("        " + ", ".join(vals) + ",")
        L.append("    },")

    L += ["};", ""]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"已写入 {path}")


if __name__ == "__main__":
    main()
