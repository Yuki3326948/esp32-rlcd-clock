def draw_grid(d, x0, y0, x1, y1, step):
    for x in range(x0, x1 + 1, step):
        d.line([x, y0, x, y1], fill=INK, width=1)
    for y in range(y0, y1 + 1, step):
        d.line([x0, y, x1, y], fill=INK, width=1)


def draw_glyph(d, rows, gx, gy, scale):
    for r, row in enumerate(rows):
        for c, p in enumerate(row):
            if p == "#":
                x, y = gx + c * scale, gy + r * scale
                d.rectangle([x, y, x + scale - 1, y + scale - 1], fill=INK)


def draw_colon(d, x, y, scale, colonw):
    """方点:2x2 个设计点。竖向压在设计点上"""
    s = scale * 2
    x0 = x + (colonw - s) // 2
    d.rectangle([x0, y + scale * 3, x0 + s - 1, y + scale * 5 - 1], fill=INK)
    d.rectangle([x0, y + scale * 11, x0 + s - 1, y + scale * 13 - 1], fill=INK)


def draw_clock(d, text, x0, y0, rows, scale, pad, colonw):
    """整串居中画在 (x0, y0) 起。返回总宽"""
    gw = len(rows["0"][0]) * scale
    x = x0
    for ch in text:
        if ch == ":":
            draw_colon(d, x, y0, scale, colonw)
            x += colonw
        else:
            draw_glyph(d, rows[ch], x, y0, scale)
            x += gw + pad
    return x - pad - x0


def label(d, text, x, y):
    f = ImageFont.truetype(FONT_UI, 15)
    d.text((x, y), text, font=f, fill=INK)


