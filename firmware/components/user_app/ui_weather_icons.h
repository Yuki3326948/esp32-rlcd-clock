/*
 * WMO 天气码 -> 图标下标。
 * 码是 open-meteo 用的 WMO 4677 那套。这里把二十几个码收敛到 7 个图标:
 *   0           晴            -> SUN
 *   1, 2        少云 / 多云    -> PARTLY
 *   3           阴            -> CLOUD
 *   45, 48      雾            -> FOG
 *   51~57       毛毛雨        -> RAIN
 *   61~67,80~82 雨 / 阵雨     -> RAIN
 *   71~77,85,86 雪 / 阵雪     -> SNOW
 *   95,96,99    雷阵雨        -> THUNDER
 * 认不出来的码一律给 CLOUD(最中性的那个),别让屏上出现空白。
 */
static inline int Weather_IconForWmo(int code)
{
    if (code == 0)                        return 0;   /* SUN     */
    if (code == 1 || code == 2)           return 1;   /* PARTLY  */
    if (code == 3)                        return 2;   /* CLOUD   */
    if (code == 45 || code == 48)         return 3;   /* FOG     */
    if (code >= 51 && code <= 67)         return 4;   /* RAIN    */
    if (code >= 80 && code <= 82)         return 4;   /* RAIN    */
    if ((code >= 71 && code <= 77) ||
        code == 85 || code == 86)         return 5;   /* SNOW    */
    if (code >= 95)                       return 6;   /* THUNDER */
    return 2;                                         /* 兜底:云 */
}
